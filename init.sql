-- =====================================================================

-- 1. Create Students Table
CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    student_uid VARCHAR2(50) NOT NULL UNIQUE,
    branch VARCHAR2(50) NOT NULL
);

-- 2. Create Semesters Table
CREATE TABLE semesters (
    semester_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    semester_number NUMBER NOT NULL,
    CONSTRAINT fk_sem_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT unq_student_semester UNIQUE(student_id, semester_number)
);

-- 3. Create Subjects Table
CREATE TABLE subjects (
    subject_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name VARCHAR2(100) NOT NULL,
    credits NUMBER NOT NULL
);

-- 4. Create Grades Table
CREATE TABLE grades (
    grade_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    semester_id NUMBER NOT NULL,
    subject_id NUMBER NOT NULL,
    grade VARCHAR2(10) NOT NULL,
    grade_point NUMBER NOT NULL,
    CONSTRAINT fk_grd_student FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_grd_semester FOREIGN KEY (semester_id) REFERENCES semesters(semester_id) ON DELETE CASCADE,
    CONSTRAINT fk_grd_subject FOREIGN KEY (subject_id) REFERENCES subjects(subject_id) ON DELETE CASCADE,
    CONSTRAINT unq_student_grade UNIQUE(student_id, semester_id, subject_id)
);

COMMIT;
